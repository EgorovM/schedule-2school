def normalize(subject: str) -> str:
    """Приводит название предмета из расписания к ключу таблиц СанПиН."""
    s = " ".join(str(subject).lower().replace("ё", "е").split())
    s = s.strip(" .")
    if s in ALIASES:
        return ALIASES[s] or s
    return s


def difficulty(subject: str, grade: int, overrides: dict | None = None) -> int | None:
    """Балл трудности предмета для класса. None — если предмет не нормирован."""
    key = normalize(subject)
    if overrides:
        by_subject = overrides.get(key) or overrides.get(str(subject).lower())
        if isinstance(by_subject, dict):
            v = by_subject.get(str(grade))
            if v is not None:
                return int(v)
        elif isinstance(by_subject, int):
            return by_subject
    if grade <= 4:
        return NOO.get(key)
    if grade <= 9:
        row = OOO.get(key)
        return row[grade - 5] if row else None
    return SOO.get(key)


def max_week(grade: int, days: int = 6) -> int | None:
    table = MAX_PER_WEEK_6DAY if days == 6 else MAX_PER_WEEK_5DAY
    return table.get(grade)


def max_day(grade: int) -> dict:
    return MAX_PER_DAY.get(grade, {"norm": 7, "relief": 7})
